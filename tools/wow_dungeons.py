# Writes scripts/Shared/WowDungeons.Data.cs from the OpenMap addon's tables: each dungeon and raid with a map of its own
# (Data/DungeonMaps.lua: its floors, their names and wings) and where its entrance is (Data/Places.lua: continent and
# yards, X north, Y west). Entrances on a zone map only (WoW Forever's new dungeons) and dungeons without floor art are
# left out: there's nothing to go into. The floor pictures themselves come from the game's files (tools/wow_dungeon_art.py).
# Run: py -I tools/wow_dungeons.py "<OpenMap folder>"
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "scripts", "Shared", "WowDungeons.Data.cs")


def cs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    data = os.path.join(sys.argv[1], "Data")
    maps = open(os.path.join(data, "DungeonMaps.lua"), encoding="utf-8").read()
    places = open(os.path.join(data, "Places.lua"), encoding="utf-8").read()

    # [id] = { -- Name \n { tiles = {...}, name = "...", wing = "..." }, ... },
    dungeons = {}
    for m in re.finditer(r"^\t\[(\d+)\] = \{ -- (.+?)\n(.*?)^\t\},", maps, re.M | re.S):
        floors = []
        for f in re.finditer(r"\{ tiles = \{[^}]*\}(.*?)\},?\n", m.group(3)):
            name = re.search(r'name = "([^"]*)"', f.group(1))
            wing = re.search(r'wing = "([^"]*)"', f.group(1))
            floors.append((name.group(1) if name else None, wing.group(1) if wing else None))
        dungeons[int(m.group(1))] = (m.group(2).strip(), floors)

    block = re.search(r"\tinstances = \{\n(.*?)\n\t\},", places, re.S).group(1)
    entrances, info = [], {}
    for line in block.splitlines():
        head = re.match(r"\s*\{ (nil|\d+), (-?[\d.]+), (-?[\d.]+), \{ (.*) \} \}", line)
        if not head or head.group(1) == "nil":
            continue
        ways = []
        for w in re.finditer(r'\{ (\d+), "([^"]*)", (true|false), (nil|\d+), (nil|\d+) \}', head.group(4)):
            mid = int(w.group(1))
            if mid not in dungeons:
                continue
            ways.append((mid, w.group(2)))
            info.setdefault(mid, (w.group(3) == "true", w.group(4), w.group(5)))
        if ways:
            entrances.append((int(head.group(1)), float(head.group(2)), float(head.group(3)), ways))

    out = ["// Generated by tools/wow_dungeons.py from the OpenMap addon's Data/DungeonMaps.lua and Data/Places.lua; regenerate rather than edit.",
           "namespace QuizNight.Shared;", "", "public static partial class WowDungeons", "{",
           "\tstatic readonly Dungeon[] All =", "\t{"]
    for mid, (name, floors) in sorted(dungeons.items()):
        if mid not in info:
            continue
        raid, lo, hi = info[mid]
        fl = ", ".join(f"new({cs(n) if n else 'null'}, {cs(w) if w else 'null'})" for n, w in floors)
        out.append(f"\t\tnew({mid}, {cs(name)}, {'true' if raid else 'false'}, {lo if lo != 'nil' else 'null'}, {hi if hi != 'nil' else 'null'}, new Floor[] {{ {fl} }}),")
    out += ["\t};", "", "\tstatic readonly Entrance[] Doors =", "\t{"]
    for c, x, y, ways in entrances:
        w = ", ".join(f"({mid}, {cs(n)})" for mid, n in ways)
        out.append(f"\t\tnew({c}, {x}, {y}, new (int, string)[] {{ {w} }}),")
    out += ["\t};", "}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"{len(info)} dungeons, {len(entrances)} entrances -> {OUT}")


if __name__ == "__main__":
    main()
